use std::fs;

use anyhow::{Context as _, Result, bail, ensure};
use clap::Parser;

use crate::product_manifest::{ProductManifest, workspace_root};

const GENERATED_PATH: &str = "crates/product_flavor/generated_product.rs";

#[derive(Clone, Debug, Parser)]
pub struct ProductsArgs {
    /// Verify generated product metadata without modifying it.
    #[arg(long)]
    pub check: bool,
}

pub fn run(args: ProductsArgs) -> Result<()> {
    let manifest = ProductManifest::load()?;
    let rust = manifest.product("rust")?;
    let generated = render(rust);
    let path = workspace_root().join(GENERATED_PATH);
    if args.check {
        let existing = fs::read_to_string(&path)
            .with_context(|| format!("failed to read {}", path.display()))?;
        if existing != generated {
            bail!("{} is stale; run `cargo xtask products`", path.display());
        }
        audit_phase_one_consumers()?;
    } else {
        fs::write(&path, generated)
            .with_context(|| format!("failed to write {}", path.display()))?;
    }
    Ok(())
}

fn audit_phase_one_consumers() -> Result<()> {
    let root = workspace_root();
    let runtime_and_packaging_consumers = [
        "script/bundle-linux",
        "script/bundle-mac",
        "script/bundle-windows.ps1",
        "crates/zed/resources/windows/zed.iss",
        "crates/zed/resources/zed.desktop.in",
        "crates/paths/src/paths.rs",
        "crates/release_channel/src/lib.rs",
        "crates/onboarding/src/onboarding.rs",
        "crates/onboarding/src/basics_page.rs",
        "crates/auto_update/src/auto_update.rs",
        "crates/auto_update_helper/src/auto_update_helper.rs",
        "crates/auto_update_helper/src/updater.rs",
    ];
    for relative_path in runtime_and_packaging_consumers {
        let path = root.join(relative_path);
        let source = fs::read_to_string(&path)
            .with_context(|| format!("failed to audit {}", path.display()))?;
        ensure_no_legacy_marketing_literal(relative_path, &source)?;
    }

    let ci = fs::read_to_string(root.join(".github/workflows/run_tests.yml"))?;
    let release = fs::read_to_string(root.join(".github/workflows/release.yml"))?;
    for (name, workflow) in [("CI", &ci), ("release", &release)] {
        for forbidden in [
            "Rustlings",
            "repository_owner",
            "namespace-profile",
            "self-hosted",
            "simtropolis/zed",
        ] {
            ensure!(
                !workflow.contains(forbidden),
                "{name} workflow contains forbidden product/orchestration value `{forbidden}`"
            );
        }
    }
    ensure!(
        ci.contains("application_features: multiplayer-tools,rust-tools")
            && ci.contains("remote_features: rust-tools"),
        "CI workflow is missing the exact Rust product feature row"
    );
    ensure!(
        release.contains("cargo xtask bundle --product")
            && release.contains("needs:\n    - product_builds")
            && release.matches("contents: write").count() == 1,
        "release workflow is missing product bundling, all-build fan-in, or minimal permissions"
    );
    Ok(())
}

fn ensure_no_legacy_marketing_literal(path: &str, source: &str) -> Result<()> {
    anyhow::ensure!(
        !source.contains("Rustlings"),
        "{path} contains a hard-coded legacy marketing name"
    );
    Ok(())
}

fn render(product: &crate::product_manifest::Product) -> String {
    let strings = |values: &[String]| {
        values
            .iter()
            .map(|value| format!("{value:?}"))
            .collect::<Vec<_>>()
            .join(", ")
    };
    format!(
        concat!(
            "// @generated by `cargo xtask products`; do not edit.\n",
            "/// The stable selected product ID.\npub const ID: &str = {id:?};\n",
            "/// The selected product's user-facing name.\npub const DISPLAY_NAME: &str = {display:?};\n",
            "/// Error title shown when installing the product CLI fails.\npub const INSTALL_CLI_ERROR_TITLE: &str = {install_cli_error_title:?};\n",
            "/// Error title shown when registering the product URL scheme fails.\npub const REGISTER_SCHEME_ERROR_TITLE: &str = {register_scheme_error_title:?};\n",
            "/// Development-channel display name.\npub const DEV_DISPLAY_NAME: &str = {dev_display:?};\n",
            "/// Nightly-channel display name.\npub const NIGHTLY_DISPLAY_NAME: &str = {nightly_display:?};\n",
            "/// Preview-channel display name.\npub const PREVIEW_DISPLAY_NAME: &str = {preview_display:?};\n",
            "/// The selected product's installed executable basename.\npub const EXECUTABLE_NAME: &str = {executable:?};\n",
            "/// The selected product's reverse-DNS bundle identifier.\npub const BUNDLE_IDENTIFIER: &str = {bundle:?};\n",
            "/// Development-channel application identifier.\npub const DEV_BUNDLE_IDENTIFIER: &str = {dev_bundle:?};\n",
            "/// Nightly-channel application identifier.\npub const NIGHTLY_BUNDLE_IDENTIFIER: &str = {nightly_bundle:?};\n",
            "/// Preview-channel application identifier.\npub const PREVIEW_BUNDLE_IDENTIFIER: &str = {preview_bundle:?};\n",
            "/// The selected product's registered URL scheme.\npub const URL_SCHEME: &str = {scheme:?};\n",
            "/// Public deep-link prefix.\npub const URL_PREFIX: &str = {url_prefix:?};\n",
            "/// Private CLI transport prefix.\npub const CLI_URL_PREFIX: &str = {cli_url_prefix:?};\n",
            "/// Private dock-action transport prefix.\npub const DOCK_ACTION_URL_PREFIX: &str = {dock_url_prefix:?};\n",
            "/// The selected product's stable global data namespace.\npub const DATA_NAMESPACE: &str = {data:?};\n",
            "/// Development-channel data namespace.\npub const DEV_DATA_NAMESPACE: &str = {dev_data:?};\n",
            "/// Nightly-channel data namespace.\npub const NIGHTLY_DATA_NAMESPACE: &str = {nightly_data:?};\n",
            "/// Preview-channel data namespace.\npub const PREVIEW_DATA_NAMESPACE: &str = {preview_data:?};\n",
            "/// Prefix for temporary update directories.\npub const AUTO_UPDATE_DIR_PREFIX: &str = {update_dir_prefix:?};\n",
            "/// Development-channel update directory prefix.\npub const DEV_AUTO_UPDATE_DIR_PREFIX: &str = {dev_update_dir_prefix:?};\n",
            "/// Nightly-channel update directory prefix.\npub const NIGHTLY_AUTO_UPDATE_DIR_PREFIX: &str = {nightly_update_dir_prefix:?};\n",
            "/// Preview-channel update directory prefix.\npub const PREVIEW_AUTO_UPDATE_DIR_PREFIX: &str = {preview_update_dir_prefix:?};\n",
            "/// Remote-server installation directory name.\npub const REMOTE_SERVER_DIR: &str = {remote_server_dir:?};\n",
            "/// Development-channel remote-server directory name.\npub const DEV_REMOTE_SERVER_DIR: &str = {dev_remote_server_dir:?};\n",
            "/// Nightly-channel remote-server directory name.\npub const NIGHTLY_REMOTE_SERVER_DIR: &str = {nightly_remote_server_dir:?};\n",
            "/// Preview-channel remote-server directory name.\npub const PREVIEW_REMOTE_SERVER_DIR: &str = {preview_remote_server_dir:?};\n",
            "/// WSL remote-server installation directory name.\npub const REMOTE_WSL_SERVER_DIR: &str = {remote_wsl_server_dir:?};\n",
            "/// Development-channel WSL remote-server directory name.\npub const DEV_REMOTE_WSL_SERVER_DIR: &str = {dev_remote_wsl_server_dir:?};\n",
            "/// Nightly-channel WSL remote-server directory name.\npub const NIGHTLY_REMOTE_WSL_SERVER_DIR: &str = {nightly_remote_wsl_server_dir:?};\n",
            "/// Preview-channel WSL remote-server directory name.\npub const PREVIEW_REMOTE_WSL_SERVER_DIR: &str = {preview_remote_wsl_server_dir:?};\n",
            "/// The selected product's update-feed namespace.\npub const UPDATE_NAMESPACE: &str = {update:?};\n",
            "/// Product-specific offset for loopback single-instance coordination.\npub const INSTANCE_PORT_OFFSET: u16 = {instance_port_offset};\n",
            "/// The selected product's agent profile ID.\npub const AGENT_PROFILE: &str = {profile:?};\n",
            "/// The selected product's agent profile display name.\npub const AGENT_PROFILE_NAME: &str = {profile_name:?};\n",
            "/// The selected product's Rust-focused agent instructions.\npub const AGENT_INSTRUCTIONS: &str = include_str!(concat!(env!(\"CARGO_MANIFEST_DIR\"), \"/../../{instructions}\"));\n",
            "/// Product Cargo features for the application package.\npub const CARGO_FEATURES: &[&str] = &[{features}];\n",
            "/// Product Cargo features for the remote server package.\npub const REMOTE_SERVER_FEATURES: &[&str] = &[{remote_features}];\n",
            "/// Product language-server defaults.\npub const DEFAULT_LANGUAGE_SERVERS: &[&str] = &[{language_servers}];\n",
            "/// Product extension defaults.\npub const DEFAULT_EXTENSIONS: &[&str] = &[{extensions}];\n",
            "/// Product toolchain onboarding handler ID.\npub const TOOLCHAIN_ONBOARDING: &str = {toolchain_onboarding:?};\n",
        ),
        id = product.id,
        display = product.display_name,
        install_cli_error_title = format!("Cannot install the {} CLI", product.display_name),
        register_scheme_error_title = format!("Error registering {} scheme", product.url_scheme),
        dev_display = format!("{} Dev", product.display_name),
        nightly_display = format!("{} Nightly", product.display_name),
        preview_display = format!("{} Preview", product.display_name),
        executable = product.executable_name,
        bundle = product.bundle_identifier,
        dev_bundle = format!("{}.dev", product.bundle_identifier),
        nightly_bundle = format!("{}.nightly", product.bundle_identifier),
        preview_bundle = format!("{}.preview", product.bundle_identifier),
        scheme = product.url_scheme,
        url_prefix = format!("{}://", product.url_scheme),
        cli_url_prefix = format!("{}-cli://", product.url_scheme),
        dock_url_prefix = format!("{}-dock-action://", product.url_scheme),
        data = product.data_namespace,
        dev_data = format!("{}-dev", product.data_namespace),
        nightly_data = format!("{}-nightly", product.data_namespace),
        preview_data = format!("{}-preview", product.data_namespace),
        update_dir_prefix = format!("{}-auto-update", product.data_namespace),
        dev_update_dir_prefix = format!("{}-dev-auto-update", product.data_namespace),
        nightly_update_dir_prefix = format!("{}-nightly-auto-update", product.data_namespace),
        preview_update_dir_prefix = format!("{}-preview-auto-update", product.data_namespace),
        remote_server_dir = format!(".{}_server", product.data_namespace),
        dev_remote_server_dir = format!(".{}-dev_server", product.data_namespace),
        nightly_remote_server_dir = format!(".{}-nightly_server", product.data_namespace),
        preview_remote_server_dir = format!(".{}-preview_server", product.data_namespace),
        remote_wsl_server_dir = format!(".{}_wsl_server", product.data_namespace),
        dev_remote_wsl_server_dir = format!(".{}-dev_wsl_server", product.data_namespace),
        nightly_remote_wsl_server_dir = format!(".{}-nightly_wsl_server", product.data_namespace),
        preview_remote_wsl_server_dir = format!(".{}-preview_wsl_server", product.data_namespace),
        update = product.update_namespace,
        instance_port_offset = product.instance_port_offset,
        profile = product.agent_profile,
        profile_name = product.agent_profile_name,
        instructions = product.agent_instructions,
        features = strings(&product.cargo_features),
        remote_features = strings(&product.remote_server_features),
        language_servers = strings(&product.default_language_servers),
        extensions = strings(&product.default_extensions),
        toolchain_onboarding = product.toolchain_onboarding,
    )
}
